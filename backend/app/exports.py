"""Markdown export of an audit report."""

from __future__ import annotations

from app.schemas import Report


def report_to_markdown(report: Report) -> str:
    lines = [
        f"# SEO & AI Visibility Audit: {report.url}",
        "",
        f"Generated {report.generated_at:%Y-%m-%d %H:%M} UTC · audit type: {report.audit_type}"
        f" · business type: {report.business_type or 'n/a'}",
        "",
        f"**Search SEO score:** {report.seo_score if report.seo_score is not None else 'n/a'}/100  ",
        f"**AI Visibility score:** {report.ai_score if report.ai_score is not None else 'n/a'}/100",
        "",
        "## The short version",
        "",
        report.executive_summary,
        "",
        "## Score by area",
        "",
        "| Category | Score | Status |",
        "|---|---|---|",
    ]
    for c in report.categories:
        lines.append(f"| {c.label} | {c.score if c.score is not None else 'n/a'} | {c.status} |")
    lines += ["", "## What to fix", ""]
    for r in report.recommendations:
        lines += [
            f"### {r.id}. {r.title}",
            "",
            f"**Priority:** {r.priority} · **Benefit:** {r.impact} · **Work needed:** {r.effort}",
            "",
        ]
        if r.observation:
            lines += [f"**What we found:** {r.observation}", ""]
        if r.action:
            lines += [f"**What to do:** {r.action}", ""]
        if r.depends_on:
            lines += [f"**Do these first:** {', '.join(r.depends_on)}", ""]
        if r.failure_check:
            lines += [f"**How you will know it did not work:** {r.failure_check}", ""]
        if r.leading_indicator:
            lines += [f"**Early sign it is working:** {r.leading_indicator}", ""]
        if r.fix_snippet:
            lines += [f"```{r.fix_snippet.language}", r.fix_snippet.code, "```", ""]
    if report.phases:
        lines += ["## Plan", ""]
        for ph in report.phases:
            lines.append(f"- **{ph.name}** ({ph.timeframe}): {', '.join(ph.items) or 'none'}")
        lines.append("")
    if report.warnings:
        lines += ["## Notes", "", *[f"- {w}" for w in report.warnings], ""]
    lines += ["---", "Generated by Radian Agents."]
    return "\n".join(lines)
